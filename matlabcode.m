%% Function to calculate powerdensity
%
function [powerdensity]=nier4(acl,height_man,distance,ptx,cableloss,mechanicaldowntilt,antennadepangles,antennagain)
          if distance>-25 && distance<-2
       virtualantheight=acl-12-height_man;% 12=height of building
          elseif distance>=-2 && distance<12 
virtualantheight=acl-height_man;%[metres]to find r deduct height of man from acl
      elseif distance>=12 && distance<=27
      virtualantheight=acl-11-height_man;% 11=height of building
     
          elseif distance>27 && distance<37
       virtualantheight=acl-height_man;
          elseif distance>=37 && distance<=47

               virtualantheight=acl-14-height_man;%14=height of building
               
       elseif distance>47

       virtualantheight=acl-height_man;
          
             end
  
  
r=sqrt(virtualantheight^2+distance^2);  %[metres]find r
theta=atand(virtualantheight/distance); %[degrees]fing dep angle

if  distance>=0
   if theta>=0
    theta=-theta;
   end
elseif distance<0
    theta=-theta;
        theta=180-theta;
        theta=-theta;
end
if(mechanicaldowntilt ~=0)
   theta=theta+mechanicaldowntilt;
end
lossfactor=10^(-cableloss/10); %[--]find cable loss
poutput=lossfactor*ptx; %[watts]multiply cable loss factor with ptx to find actual transmitted power

b=sum(antennadepangles>(theta));
ang1=antennadepangles(b);
ang2=antennadepangles(b+1);
gain1=antennagain(b);
gain2=antennagain(b+1);
m=(gain2-gain1)/(ang2-ang1);

c=gain2-(m*ang2);

antgain=m*+theta+c; %antenna gain in dbd
antgainindbi=antgain+2.15; %antenna gain in dbi
antennagf=10^(antgainindbi/10);
eirp=antennagf*poutput*1000;%eirp in mW
powerdensity=eirp/(4*pi*r*r*100*100);%power density in mW/sq.-cm
end

